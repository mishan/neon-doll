# --- Kvantum -----------------------------------------------------------------
#
# A Kvantum theme is a config and an SVG. Each widget section names SVG
# elements; a boxed element is nine pieces, the interior "NAME-STATE" and the
# frame "NAME-STATE-top", "-topleft" and so on, which Kvantum stretches to the
# frame widths the section gives. So the frame widths here and the pieces in
# the SVG come from the same table, and a 1px line in the SVG is 1px on screen.
# States are normal, focused (hover), pressed, toggled and disabled; a missing
# state falls back to normal, and a missing normal to Kvantum's default theme,
# which has gradients, so every element named here has a normal.

class Svg:
    """Elements packed onto a sheet, left to right, in rows."""

    def __init__(self):
        self.body, self.x, self.y, self.row = [], 0, 0, 0

    def place(self, w, h):
        gap = 4
        if self.x + w > 1000:
            self.x, self.y, self.row = 0, self.y + self.row + gap, 0
        at = (self.x, self.y)
        self.x += w + gap
        self.row = max(self.row, h)
        return at

    def group(self, id, x, y, w, h, shapes):
        """One element: an invisible rect that fixes its bounds, then its
        shapes, which are in the element's own coordinates."""
        out = [f'<g id="{id}">', f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="#000" fill-opacity="0"/>']
        for s in shapes:
            out.append(s(x, y))
        out.append("</g>")
        self.body.append("".join(out))

    def element(self, id, w, h, shapes):
        x, y = self.place(w, h)
        self.group(id, x, y, w, h, shapes)

    def svg(self, comment):
        height = self.y + self.row
        return (
            '<?xml version="1.0" encoding="UTF-8"?>\n'
            f"<!-- {comment} -->\n"
            f'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="{height}" '
            f'viewBox="0 0 1000 {height}">\n' + "\n".join(self.body) + "\n</svg>\n"
        )


def paint(c):
    """(color, alpha) or a plain color, as SVG fill attributes."""
    color, alpha = c if isinstance(c, tuple) else (c, 1)
    return f'fill="{color}"' + (f' fill-opacity="{alpha:g}"' if alpha < 1 else "")


def rect(x, y, w, h, c):
    return lambda ox, oy: f'<rect x="{ox + x:g}" y="{oy + y:g}" width="{w:g}" height="{h:g}" {paint(c)}/>'


def circle(cx, cy, r, c):
    return lambda ox, oy: f'<circle cx="{ox + cx:g}" cy="{oy + cy:g}" r="{r:g}" {paint(c)}/>'


def ring(cx, cy, r, width, c):
    color, alpha = c if isinstance(c, tuple) else (c, 1)
    op = f' stroke-opacity="{alpha:g}"' if alpha < 1 else ""
    return lambda ox, oy: (f'<circle cx="{ox + cx:g}" cy="{oy + cy:g}" r="{r - width / 2:g}" fill="none" '
                           f'stroke="{color}" stroke-width="{width:g}"{op}/>')


def line(points, c, width=2):
    """A stroked polyline, square-ended and mitered: no round corners here
    either."""
    def f(ox, oy):
        d = "M" + " L".join(f"{ox + x:g},{oy + y:g}" for x, y in points)
        return (f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{width:g}" '
                'stroke-linecap="square" stroke-linejoin="miter"/>')
    return f


def box(svg, name, state, frame, fill=None, edges=None, inset=(0, 0, 0, 0), core=8):
    """A nine-piece element. frame is (top, bottom, left, right), as in the
    config; fill covers the box, frame included unless inset keeps it off,
    so padding in the frame reads as interior; edges maps a side to (width,
    color), drawn over the fill at the outside of that side. A state of None
    is for the stateless elements, like the focus frame."""
    t, b, l, r = frame
    w, h = l + core + r, t + core + b
    edges = edges or {}
    it, ib, il, ir = inset
    layers = [(il, it, w - il - ir, h - it - ib, fill)] if fill else []
    et = edges.get("top", (0, None))[0]
    eb = edges.get("bottom", (0, None))[0]
    for side, (ew, c) in edges.items():
        if not ew:
            continue
        layers.append({
            "top": (0, 0, w, ew, c),
            "bottom": (0, h - ew, w, ew, c),
            "left": (0, et, ew, h - et - eb, c),
            "right": (w - ew, et, ew, h - et - eb, c),
        }[side])
    pieces = {
        "topleft": (0, 0, l, t), "top": (l, 0, core, t), "topright": (l + core, 0, r, t),
        "left": (0, t, l, core), "": (l, t, core, core), "right": (l + core, t, r, core),
        "bottomleft": (0, t + core, l, b), "bottom": (l, t + core, core, b),
        "bottomright": (l + core, t + core, r, b),
    }
    ox, oy = svg.place(w, h)
    for pos, (px, py, pw, ph) in pieces.items():
        if pw <= 0 or ph <= 0:
            continue
        shapes = []
        for lx, ly, lw, lh, c in layers:
            x0, y0 = max(px, lx), max(py, ly)
            x1, y1 = min(px + pw, lx + lw), min(py + ph, ly + lh)
            if x1 > x0 and y1 > y0:
                shapes.append(rect(x0 - px, y0 - py, x1 - x0, y1 - y0, c))
        id = (name if state is None else f"{name}-{state}") + (f"-{pos}" if pos else "")
        svg.group(id, ox + px, oy + py, pw, ph, shapes)


def outline(width, c, sides=("top", "bottom", "left", "right")):
    return {s: (width, c) for s in sides}


