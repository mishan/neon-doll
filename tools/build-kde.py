def colors(variant):
    """The palette, with every tint both flattened (for formats that take
    only solid colors) and as (color, alpha) (for the SVG, which blends)."""
    p = tokens.flat(variant)
    a = {name: tokens.tint(variant, name) for name in tokens.tints(variant)}
    return p, a


def rgb(h):
    return ",".join(map(str, tokens.rgb(h)))


def generated():
    return "Generated by tools/build-kde.py; edit that, not this."


# --- Plasma color schemes ----------------------------------------------------

def disabled_fade(p):
    """Plasma dims disabled text by fading it toward its background. The fade
    that takes ink closest to dimmest, which is what disabled text is on
    every other part of the theme."""
    ink, bg, want = (tokens.rgb(p[k]) for k in ("ink", "bg", "dimmest"))
    num = sum((b - i) * (w - i) for i, b, w in zip(ink, bg, want))
    den = sum((b - i) ** 2 for i, b in zip(ink, bg))
    return round(num / den, 2)


