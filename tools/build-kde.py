def qtct(variant):
    p, _ = colors(variant)
    # QPalette's roles, in its order. Qt 6.6 added a 22nd, Accent, but
    # qt6ct's own schemes stop at 21, and so does this, for both.
    roles = {
        "WindowText": p["ink"], "Button": p["wash"], "Light": p["line"],
        "Midlight": p["line"], "Dark": p["bg"], "Mid": p["line"], "Text": p["ink"],
        "BrightText": p["pink"], "ButtonText": p["ink"], "Base": p["bg"],
        "Window": p["bg"], "Shadow": p["bg"], "Highlight": p["select"],
        "HighlightedText": p["ink"], "Link": p["purple"], "LinkVisited": p["purple"],
        "AlternateBase": p["wash"], "NoRole": p["bg"], "ToolTipBase": p["panel"],
        "ToolTipText": p["ink"], "PlaceholderText": p["dimmest"],
    }
    inactive = roles | {"Highlight": p["press"]}
    disabled = roles | {k: p["dimmest"] for k in ("WindowText", "Text", "ButtonText", "HighlightedText")}

    def row(r):
        return ", ".join(f"#ff{v.lstrip('#')}" for v in r.values())

    return "\n".join([
        "[ColorScheme]",
        f"active_colors={row(roles)}",
        f"disabled_colors={row(disabled)}",
        f"inactive_colors={row(inactive)}",
        "",
    ])


def outputs():
    for v in VARIANTS:
        yield OUT / "color-schemes" / f"{SCHEME[v]}.colors", color_scheme(v)
        yield OUT / "Kvantum" / "NeonDoll" / f"{KVANTUM[v]}.kvconfig", kvantum_config(v)
        yield OUT / "Kvantum" / "NeonDoll" / f"{KVANTUM[v]}.svg", kvantum_svg(v)
        yield from look_and_feel(v)
        yield OUT / "konsole" / f"{SCHEME[v]}.colorscheme", konsole_scheme(v)
        yield OUT / "konsole" / f"{NAME[v]}.profile", konsole_profile(v)
        yield OUT / "syntax-highlighting" / f"neon-doll-{v}.theme", syntax_theme(v)
        yield OUT / "qtct" / f"{SCHEME[v]}.conf", qtct(v)


def main():
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs():
        data = text.encode()
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(path.relative_to(ROOT))
    if stale:
        sys.exit("stale: " + ", ".join(map(str, stale)) + " (run tools/build-kde.py)")


main()
